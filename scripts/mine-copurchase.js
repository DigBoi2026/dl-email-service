// scripts/mine-copurchase.js — the "smart" layer, learned from YOUR real orders.
//
//   SHOPIFY_STORE=xxx.myshopify.com SHOPIFY_ADMIN_TOKEN=shpat_xxx \
//     node scripts/mine-copurchase.js
//
// Walks your paid order history, classifies each line item into a product key using
// the SAME match terms as config/recommend.json, counts which products actually get
// bought together, and writes config/copurchase.json.
//
// WHY BUILD TIME, NOT REQUEST TIME: the learning happens here, once, on your laptop.
// At request time it's a static JSON lookup — 0ms, no API call, no model, no
// hallucination. Re-run it monthly (or when the catalog changes) and redeploy.
//
// The maths is deliberately simple and inspectable:
//   support(A,B)    = number of orders containing both
//   confidence(A→B) = support(A,B) / count(A)   ... "of people who bought A, what
//                                                    share also bought B"
// Thresholds live in config/recommend.json → copurchase.minSupport / minConfidence.
// Low support = noise; that's why the default floor is 5 orders. If your data is
// too thin to clear the floor, NOTHING is recommended from this layer and your
// rules + fallback carry it — which is the correct behaviour, not a failure.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { shopifyGQL } from "../lib/shopify.js";
import { classify } from "../lib/recommend.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const cfgPath = path.join(__dirname, "..", "config", "recommend.json");
const outPath = path.join(__dirname, "..", "config", "copurchase.json");
const cfg = JSON.parse(fs.readFileSync(cfgPath, "utf8"));

const MAX_ORDERS = parseInt(process.env.MAX_ORDERS || "1000", 10);

async function fetchOrders() {
  const orders = [];
  let cursor = null;
  while (orders.length < MAX_ORDERS) {
    const data = await shopifyGQL(
      `query($n: Int!, $after: String) {
         orders(first: $n, after: $after, query: "financial_status:paid", reverse: true) {
           pageInfo { hasNextPage endCursor }
           nodes { lineItems(first: 50) { nodes { title } } }
         }
       }`,
      { n: Math.min(100, MAX_ORDERS - orders.length), after: cursor }
    );
    const page = data.orders;
    orders.push(...page.nodes.map((o) => o.lineItems.nodes.map((li) => li.title)));
    process.stdout.write(`\r  fetched ${orders.length} orders...`);
    if (!page.pageInfo.hasNextPage) break;
    cursor = page.pageInfo.endCursor;
  }
  process.stdout.write("\n");
  return orders;
}

function mine(orders) {
  const count = new Map();      // key → orders containing it
  const pairCount = new Map();  // "a|b" → orders containing both

  for (const titles of orders) {
    const keys = [...classify(titles, cfg)];
    for (const k of keys) count.set(k, (count.get(k) || 0) + 1);
    for (let i = 0; i < keys.length; i++)
      for (let j = 0; j < keys.length; j++) {
        if (i === j) continue;
        const id = `${keys[i]}|${keys[j]}`;
        pairCount.set(id, (pairCount.get(id) || 0) + 1);
      }
  }

  const pairs = {};
  for (const [id, support] of pairCount) {
    const [a, b] = id.split("|");
    const confidence = support / (count.get(a) || 1);
    (pairs[a] ||= []).push({ key: b, support, confidence: +confidence.toFixed(3) });
  }
  for (const k of Object.keys(pairs)) pairs[k].sort((x, y) => y.confidence - x.confidence);
  return { counts: Object.fromEntries(count), pairs };
}

const orders = await fetchOrders();
const { counts, pairs } = mine(orders);
const out = {
  generatedAt: new Date().toISOString(),
  ordersAnalysed: orders.length,
  productCounts: counts,
  pairs,
  _notes: "Generated by scripts/mine-copurchase.js. Do not hand-edit — re-run the script.",
};
fs.writeFileSync(outPath, JSON.stringify(out, null, 2));

console.log(`\nAnalysed ${orders.length} paid orders.`);
console.log("Product frequency:", counts);
const { minSupport = 5, minConfidence = 0.25 } = cfg.copurchase || {};
console.log(`\nPairs clearing thresholds (support>=${minSupport}, confidence>=${minConfidence}):`);
let usable = 0;
for (const [a, list] of Object.entries(pairs))
  for (const s of list)
    if (s.support >= minSupport && s.confidence >= minConfidence) {
      usable++;
      console.log(`  bought ${a} → recommend ${s.key}  (${(s.confidence * 100).toFixed(0)}% of ${counts[a]} buyers, n=${s.support})`);
    }
if (!usable) console.log("  (none — data too thin. Rules + fallback will carry it. That's fine.)");
console.log(`\nWrote ${outPath}`);
